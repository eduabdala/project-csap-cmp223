#!/usr/bin/env bash
# ============================================================
# vendor-pqc.sh — Vendor the algorithm sources into pqc/<alg>/<variant>/.
#
# Target layout (6 binaries = 3 algorithms x 2 variants):
#   pqc/kyber512/ref     pqc/kyber512/asm
#   pqc/ctru-light/ref   pqc/ctru-light/asm
#   pqc/ecdh/ref         pqc/ecdh/asm
#
# Sources:
#   - CTRU-Light + Kyber (ref and asm/AVR): CHES 2026 artifact (MIT)
#       https://github.com/whYBeKim/CTRU-Light-and-PQC-on-AVR
#   - ECDH baseline: micro-ecc (uECC). The "asm" variant uses the AVR
#       assembly routines built into micro-ecc itself (uECC_asm_avr).
#
# Usage:
#   scripts/vendor-pqc.sh [kyber512|ctru-light|ecdh|all]
#
# NOTE: the EXACT paths inside the CHES artifact must be confirmed on the first
# clone (the layout of crypto_kem/CTRU-Light and crypto_kem/kyber varies by
# version). The mappings below are marked with TODO where uncertain.
# ============================================================
set -euo pipefail

WHAT="${1:-all}"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PQC="${ROOT}/firmware/pqc"

CHES_REPO="https://github.com/whYBeKim/CTRU-Light-and-PQC-on-AVR.git"
CHES_REF="${CHES_REF:-main}"
UECC_REPO="https://github.com/kmackay/micro-ecc.git"
UECC_REF="${UECC_REF:-master}"

TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT

clone_ches() {
    if [ ! -d "${TMP}/ches" ]; then
        echo ">> Cloning CHES artifact (${CHES_REF})..."
        git clone --quiet "${CHES_REPO}" "${TMP}/ches"
        git -C "${TMP}/ches" checkout --quiet "${CHES_REF}"
    fi
}

stamp() {   # $1 = dest dir, $2 = source, $3 = repo, $4 = checkout dir
    git -C "$4" rev-parse HEAD > /dev/null
    cat > "$1/VENDOR.txt" <<EOF
Source: $2
Repo  : $3
Commit: $(git -C "$4" rev-parse HEAD)
Date  : $(date -u +%Y-%m-%dT%H:%M:%SZ)
Generated by scripts/vendor-pqc.sh. Do not edit by hand.
EOF
}

vendor_kyber() {
    clone_ches
    local base="${TMP}/ches/crypto_kem/kyber"
    echo ">> Kyber-512: ref + asm (CHES artifact)"
    # TODO: confirm the real subfolders (e.g. .../C-ref and .../Montgomery).
    mkdir -p "${PQC}/kyber512/ref" "${PQC}/kyber512/asm"
    # ref = plain C implementation
    cp -f "${base}"/C-ref/*.c "${base}"/C-ref/*.h "${PQC}/kyber512/ref/" 2>/dev/null || \
        echo "!! adjust the Kyber ref path in vendor-pqc.sh"
    # asm = Montgomery with AVR routines (.S)
    cp -f "${base}"/Montgomery/*.c "${base}"/Montgomery/*.h "${base}"/Montgomery/*.S \
        "${PQC}/kyber512/asm/" 2>/dev/null || \
        echo "!! adjust the Kyber asm path in vendor-pqc.sh"
    stamp "${PQC}/kyber512/ref" "CHES2026 kyber/C-ref" "${CHES_REPO}" "${TMP}/ches"
    stamp "${PQC}/kyber512/asm" "CHES2026 kyber/Montgomery(AVR asm)" "${CHES_REPO}" "${TMP}/ches"
}

vendor_ctru() {
    clone_ches
    local base="${TMP}/ches/crypto_kem/CTRU-Light"
    echo ">> CTRU-Light: ref + asm (CHES artifact)"
    # TODO: confirm the real subfolders (e.g. .../C-ref(SHA3) and .../Kred-ascon).
    mkdir -p "${PQC}/ctru-light/ref" "${PQC}/ctru-light/asm"
    cp -f "${base}"/C-ref*/*.c "${base}"/C-ref*/*.h "${PQC}/ctru-light/ref/" 2>/dev/null || \
        echo "!! adjust the CTRU ref path in vendor-pqc.sh"
    cp -f "${base}"/Kred-ascon/*.c "${base}"/Kred-ascon/*.h "${base}"/Kred-ascon/*.S \
        "${PQC}/ctru-light/asm/" 2>/dev/null || \
        echo "!! adjust the CTRU asm path in vendor-pqc.sh"
    stamp "${PQC}/ctru-light/ref" "CHES2026 CTRU-Light/C-ref" "${CHES_REPO}" "${TMP}/ches"
    stamp "${PQC}/ctru-light/asm" "CHES2026 CTRU-Light/Kred-ascon(AVR asm)" "${CHES_REPO}" "${TMP}/ches"
}

vendor_ecdh() {
    echo ">> ECDH: micro-ecc (ref + built-in AVR asm)"
    git clone --quiet "${UECC_REPO}" "${TMP}/uecc"
    git -C "${TMP}/uecc" checkout --quiet "${UECC_REF}"
    for v in ref asm; do
        mkdir -p "${PQC}/ecdh/${v}"
        cp -f "${TMP}/uecc/uECC.c" "${TMP}/uecc/uECC.h" "${PQC}/ecdh/${v}/"
        for f in types.h uECC_vli.h asm_arm.inc asm_avr.inc curve-specific.inc; do
            [ -f "${TMP}/uecc/${f}" ] && cp -f "${TMP}/uecc/${f}" "${PQC}/ecdh/${v}/" || true
        done
        stamp "${PQC}/ecdh/${v}" "micro-ecc (uECC)" "${UECC_REPO}" "${TMP}/uecc"
    done
    # The asm variant enables micro-ecc's AVR assembly via a build define.
    echo "   (asm variant: compile with -DuECC_PLATFORM=uECC_avr -DuECC_OPTIMIZATION_LEVEL=3)"
}

case "${WHAT}" in
    kyber512)   vendor_kyber ;;
    ctru-light) vendor_ctru ;;
    ecdh)       vendor_ecdh ;;
    all)        vendor_kyber; vendor_ctru; vendor_ecdh ;;
    *) echo "Usage: $0 [kyber512|ctru-light|ecdh|all]" >&2; exit 2 ;;
esac

echo ">> Done. Check the vendored api.h files and adjust the kem_*.c adapters if"
echo "   the symbol prefix differs (see the comments in each kem_*.c)."
